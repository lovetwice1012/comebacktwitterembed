    await page.getByRole('button', { name: 'Discordの表示例を見る', exact: true }).click();
    await page.getByRole('heading', { name: 'Discordの表示例', exact: true }).waitFor();
    await photo('desktop-settings');
    await page.getByRole('button', { name: '変更を保存', exact: true }).click();
