    await page.getByRole('link', { name: 'サーバーを選び直す', exact: true }).waitFor();
    await photo('readonly-access');
    checks.push({ check: 'restricted-access-and-media-have-safe-recovery' });
    await page.setViewportSize({ width: 1440, height: 1024 });
    for (const [route, name] of [['preview', 'desktop-preview'], ['access', 'desktop-access'], ['logs', 'desktop-history'], ['media', 'desktop-media']]) { await visit(`/dashboard/${guild}/${route}`); await photo(name); }
