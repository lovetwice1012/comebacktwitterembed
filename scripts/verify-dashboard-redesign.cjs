    await page.getByRole('button', { name: 'ロール', exact: true }).click();
    await page.getByRole('checkbox', { name: '作品レビュアー（888888888888888888）を選択', exact: true }).check();
    await page.getByRole('button', { name: '閲覧を許可', exact: true }).filter({ visible: true }).click();
    await page.getByText('1件に閲覧のみを許可しました。', { exact: true }).waitFor();
    await photo('access-role-receipt');
    checks.push({ check: 'named-user-and-role-save-receipts-readback' });
    await visit(`/dashboard/${guild}/logs`); await fit('mobile-history'); await photo('mobile-history');
