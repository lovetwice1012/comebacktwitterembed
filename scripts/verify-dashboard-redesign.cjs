    const cancelDeletion = async dialog => { confirmation = dialog.message(); await dialog.dismiss(); };
    page.once('dialog', cancelDeletion);
    await page.getByRole('button', { name: '期限切れを削除', exact: true }).click();
    assert(confirmation.includes('全サーバー共通'));
    assert.equal((await (await page.request.get(url + '/fixture/evidence')).json()).media.totalCacheCount, 28);
