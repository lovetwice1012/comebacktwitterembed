        await page.setViewportSize({ width: 390, height: 844 });
        assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
        await page.screenshot({ path: path.join(folder, 'marketplace-mobile.png'), fullPage: true });
        checked('Marketplace fits a 390px viewport');
        await page.setViewportSize({ width: 1440, height: 1000 });
        await openDictionary(json.id); await button('版の履歴').click();
