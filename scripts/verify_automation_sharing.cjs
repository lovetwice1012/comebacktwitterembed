        await expect(button('この版を導入（下書き）')).toBeDisabled();
        assert.equal((await read(`marketplace/${privatePack.id}`)).visibility, 'private');
        const publicDownload = await download('ダウンロード', 'package-download.json');
        assert(!publicDownload.includes(fragment.get('key'))); assert(!publicDownload.includes(dm.id)); assert(!publicDownload.includes('fixture-only-not-a-real-webhook'));
        checked('Public/unlisted/private UI publication and limited-share opening work; private drafts cannot be installed and downloads exclude bindings/share keys');
